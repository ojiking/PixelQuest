const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '../../static/game');
const SP = path.join(__dirname, 'out'); require('fs').mkdirSync(SP, { recursive: true });
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css' };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const errs = []; page.on('pageerror', e => errs.push(e.message + '\n' + e.stack));
  await page.route('http://game.test/**', route => { const rel = new URL(route.request().url()).pathname.replace(/^\/+/, '') || 'index.html'; route.fulfill({ status: 200, contentType: TYPES[path.extname(rel)], body: fs.readFileSync(path.join(ROOT, rel)) }); });
  await page.goto('http://game.test/index.html'); await page.waitForTimeout(1200);
  await page.keyboard.press('Enter'); await page.waitForTimeout(800);
  const ev = (f, a) => page.evaluate(f, a);
  await ev(async () => { const g = window.__game, p = g.player; for (const e of g.enemies) { e.remove = true; e.dead = true; } g.zoneIdx = g.stage.zones.length; g.lock = null; p.maxHp = p.hp = 9999; p.x = 10; p.z = 0.5; g.camX = 12; g.run.scrap = 0;
    const { Item } = await import('./js/props.js'); for (let i = 0; i < 4; i++) g.items.push(new Item('scrap', null, 13 + i * 0.6, 1.5)); });
  await page.waitForTimeout(300);
  const r = await ev(() => { const g = window.__game, p = g.player, out = [];
    const e1 = g.spawnEnemy('brute', 1); e1.x = 11.5; e1.z = 0.5; e1.cool = 99;
    g.severPart(e1, 'armF', 1, { attacker: p, mode: 'cut' }); out.push(g.run.scrap);
    g.severPart(e1, 'legB', 1, { attacker: p, mode: 'cut' }); out.push(g.run.scrap);
    g.severPart(e1, 'head', 1, { attacker: p, mode: 'cut' }); out.push(g.run.scrap);
    const e2 = g.spawnEnemy('grunt', 1); e2.x = 12; e2.z = 0.5; g.severPart(e2, 'armB', 1, { attacker: g.bot, mode: 'cut' }); out.push('bot→' + g.run.scrap);
    return out; });
  await page.waitForTimeout(250);
  console.log('scrap after arm/leg/head by hero, arm by bot:', r.join(' → '), '| texts:', await ev(() => [...document.querySelectorAll('.ftext')].map(e => e.textContent + '[' + e.className.replace('ftext ', '') + ']').join(', ')));
  await page.screenshot({ path: SP + '/85_coin.png' });
  console.log('errors', errs.length ? errs : 'none');
  await browser.close();
})();
